"""NEBULA - Core Domain Schemas for Astronomical Observations and Agent Reports.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class AnomalyClassification(str, Enum):
    """Scientific classification outcome of the anomaly investigation."""
    TRANSIENT_EVENT = "transient_event"       # Supernova, flaring star, nova
    MOVING_OBJECT = "moving_object"           # Asteroid, NEO, comet
    MEASUREMENT_ARTIFACT = "measurement_artifact" # Cosmic ray, bad pixel, saturation
    VARIABLE_SOURCE = "variable_source"       # Blazar, pulsating variable
    INCONCLUSIVE = "inconclusive"             # Insufficient data, requires follow-up


class ObservationEpoch(BaseModel):
    """A single astronomical observation epoch."""
    epoch_id: str = Field(..., description="Unique epoch identifier, e.g. 'EP-01'")
    timestamp: datetime = Field(..., description="UTC timestamp of the observation")
    telescope_id: str = Field(..., description="Observatory instrument identifier")
    filter_band: str = Field(..., description="Photometric optical/IR filter band (e.g. 'g', 'r', 'i', 'z')")
    exposure_time_sec: float = Field(..., description="Exposure duration in seconds")
    
    # Photometry
    magnitude: float = Field(..., description="Apparent magnitude in AB or Vega system")
    magnitude_err: float = Field(..., description="Photometric uncertainty (1-sigma)")
    flux_ujy: float = Field(..., description="Calibrated flux density in microJanskys (uJy)")
    flux_err_ujy: float = Field(..., description="Flux measurement uncertainty (uJy)")
    
    # Astrometry
    ra_deg: float = Field(..., description="Right Ascension in decimal degrees (J2000)")
    dec_deg: float = Field(..., description="Declination in decimal degrees (J2000)")
    position_err_arcsec: float = Field(..., description="Astrometric positional uncertainty in arcseconds")
    
    # Quality indicators
    snr: float = Field(..., description="Signal-to-noise ratio")
    psf_fwhm_arcsec: float = Field(..., description="Point Spread Function Full-Width at Half-Max")
    psf_chi2: float = Field(..., description="PSF model fit reduced chi-squared")
    quality_flags: int = Field(default=0, description="Bitmask of detector/pipeline quality flags")
    flag_descriptions: List[str] = Field(default_factory=list, description="Human-readable quality flag labels")


class AstronomicalTarget(BaseModel):
    """Astronomical object or anomaly target under investigation."""
    target_id: str = Field(..., description="Target catalog ID, e.g. 'NEBULA-OBJ-2026-X1'")
    name: str = Field(..., description="Common or survey catalog name")
    description: str = Field(..., description="Brief description of the initial detection trigger")
    expected_classification: AnomalyClassification = Field(..., description="Ground truth for benchmarking")
    dataset_type: str = Field(default="synthetic", description="Strictly 'synthetic' for simulated datasets")
    epochs: List[ObservationEpoch] = Field(..., min_length=1, description="List of observation epochs")
    discovery_notes: str = Field(default="", description="Observer or alert trigger notes")


class ToolExecutionFinding(BaseModel):
    """Structured result returned by an agent analysis tool."""
    tool_name: str = Field(..., description="Name of the tool executed")
    step_number: int = Field(..., description="Step number in the investigation")
    timestamp: datetime = Field(default_factory=utc_now)
    summary: str = Field(..., description="Concise human-readable finding summary")
    metrics: Dict[str, Any] = Field(default_factory=dict, description="Key quantitative scientific measurements")
    limitations: List[str] = Field(default_factory=list, description="Known uncertainties or observational limits")
    indicates_classification: Optional[AnomalyClassification] = Field(
        None, description="Hypothesis favored by this tool's specific evidence"
    )


class ScientificReport(BaseModel):
    """Final comprehensive evidence-based report generated by Amazon Bedrock."""
    target_id: str
    target_name: str
    executive_summary: str
    primary_classification: AnomalyClassification
    classification_confidence: float = Field(
        ..., ge=0.0, le=1.0, description="Scientific hypothesis confidence (0.0 to 1.0)"
    )
    observed_facts: List[str] = Field(
        ..., description="Firm empirical observations supported by tool data"
    )
    interpretations: List[str] = Field(
        ..., description="Physical astrophysical interpretations and modeling"
    )
    unknowns_and_uncertainties: List[str] = Field(
        ..., description="Remaining observational gaps or unresolved nuances"
    )
    evidence_references: List[str] = Field(
        ..., description="Direct references to tool metrics and step findings"
    )
    recommended_follow_up: List[str] = Field(
        ..., description="Suggested follow-up observations (e.g. spectroscopy, high-cadence astrometry)"
    )
    is_development_mode: bool = Field(
        default=False, description="Strictly True if Bedrock was unconfigured and report is simulated"
    )
    model_id: str = Field(..., description="Amazon Bedrock model ID used, e.g. anthropic.claude-3-5-sonnet")
    generated_at: datetime = Field(default_factory=utc_now)


class InvestigationSession(BaseModel):
    """Full session state representing an active or completed investigation."""
    investigation_id: str
    target: AstronomicalTarget
    user_query: str
    current_step: int = 1
    max_steps: int = 4
    status: str = "in_progress"  # "in_progress", "completed", "failed", "stopped"
    
    # Timeline and decisions
    decisions: List[Any] = Field(default_factory=list, description="List of ToolDecisionResult objects")
    tool_results: List[ToolExecutionFinding] = Field(default_factory=list)
    state_history: List[str] = Field(default_factory=list)
    
    # Final output
    final_report: Optional[ScientificReport] = None
    created_at: datetime = Field(default_factory=utc_now)
    completed_at: Optional[datetime] = None
    execution_mode: str = Field(default="live", description="Telemetry indicator of execution environment")
